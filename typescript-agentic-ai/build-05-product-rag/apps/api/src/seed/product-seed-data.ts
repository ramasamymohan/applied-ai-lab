/**
 * Synthetic product catalog for Build 05 (seed version 1).
 *
 * Everything here is invented: the brands, the products, the specifications,
 * and the prices. Any resemblance to a real brand or product is coincidental.
 * It exists so retrieval can be demonstrated on a small, self-contained
 * dataset, and must never be presented as real retail data.
 *
 * Versioning: bump PRODUCT_SEED_VERSION when the data changes meaningfully.
 * The seed script upserts by SKU, so edited rows are updated in place and
 * rows removed from this file are NOT deleted from the database.
 *
 * Attribute keys are consistent within a category (for example every rain
 * jacket has `waterproof` and `weight_g`) but vary between categories.
 *
 * A few details are deliberate, to give retrieval something real to do:
 * similar products that differ on one attribute, one-word brand names that
 * double as ordinary words, and SKUs that carry meaning only as exact tokens.
 */

import type { ProductStockStatus } from "../db/types.js";

export const PRODUCT_SEED_VERSION = 1;

export type ProductAttributeValue = string | number | boolean | string[];

export type ProductSeed = {
  sku: string;
  name: string;
  brand: string;
  category: string;
  description: string;
  attributes: Record<string, ProductAttributeValue>;
  price: number;
  currency: "USD";
  stockStatus: ProductStockStatus;
  /** Key the UI maps to a placeholder illustration. */
  imagePlaceholder: string;
};

type Attributes = Record<string, ProductAttributeValue>;

type Row = [
  sku: string,
  name: string,
  brand: string,
  price: number,
  stock: ProductStockStatus,
  attributes: Attributes,
  description: string,
];

const IN = "in_stock" as const;
const LOW = "low_stock" as const;
const OUT = "out_of_stock" as const;

function slugify(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function category(name: string, rows: Row[]): ProductSeed[] {
  return rows.map(
    ([sku, productName, brand, price, stockStatus, attributes, description]) => ({
      sku,
      name: productName,
      brand,
      category: name,
      description,
      attributes,
      price,
      currency: "USD",
      stockStatus,
      imagePlaceholder: slugify(name),
    }),
  );
}

